"""Stable signing for the owner's local GalaxyControl build (not distribution/notarization).

Only an isolated keychain and code-signing-only certificate are created. No root trust,
TCC permissions, default keychain, login keychain items or system policies are changed.
The private signing material lives outside both the app and corresponding-source ZIP.
Use an Apple-issued identity through the release pipeline for public distribution.
"""
import argparse
import hashlib
import json
import os
import pathlib
import plistlib
import secrets
import shutil
import subprocess
import tempfile

IDENTIFIER = 'local.galaxycontrol.portable'
STORE = pathlib.Path.home() / 'Library/Application Support/GalaxyControl/LocalSigning'


def run(args, **kwargs):
    result = subprocess.run(args, capture_output=True, **kwargs)
    if result.returncode:
        # Command arguments can contain the generated local keychain password.
        # Never include them in exceptions or logs.
        raise RuntimeError(pathlib.Path(args[0]).name + ' failed: ' + result.stderr.decode(errors='replace')[:1200])
    return result.stdout


def private_file(path, data):
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    with os.fdopen(fd, 'wb') as output:
        output.write(data)


def safe_store():
    for ancestor in (STORE, *STORE.parents):
        if ancestor.is_symlink():
            raise RuntimeError('Signing directory must not contain symbolic links')
    STORE.mkdir(mode=0o700, parents=True, exist_ok=True)
    if STORE.stat().st_uid != os.getuid() or STORE.stat().st_mode & 0o077:
        raise RuntimeError('Signing directory must be private to its owner')


def setup():
    safe_store()
    metadata = STORE / 'identity.json'
    if metadata.exists():
        return json.loads(metadata.read_text())
    if any(STORE.iterdir()):
        raise RuntimeError('Incomplete signing setup; preserve it for inspection rather than replacing its key')
    password = secrets.token_urlsafe(48)
    keychain = STORE / 'GalaxyControl.keychain-db'
    previous = run(['/usr/bin/security', 'list-keychains', '-d', 'user']).decode()
    search = [json.loads(line.strip()) for line in previous.splitlines() if line.strip()]
    try:
        with tempfile.TemporaryDirectory(prefix='galaxy-local-signing-') as temp:
            root = pathlib.Path(temp)
            config = root / 'certificate.cnf'
            config.write_text('''[req]
prompt = no
distinguished_name = dn
x509_extensions = code_signing
[dn]
CN = GalaxyControl Local Development
[code_signing]
basicConstraints = critical,CA:false
keyUsage = critical,digitalSignature
extendedKeyUsage = critical,codeSigning
subjectKeyIdentifier = hash
''')
            run(['/usr/bin/openssl', 'req', '-x509', '-newkey', 'rsa:3072', '-nodes',
                 '-keyout', str(root/'key.pem'), '-out', str(root/'cert.pem'), '-days', '3650',
                 '-config', str(config)])
            run(['/usr/bin/openssl', 'pkcs12', '-export', '-inkey', str(root/'key.pem'),
                 '-in', str(root/'cert.pem'), '-out', str(root/'identity.p12'), '-passout', 'stdin'],
                input=(password+'\n').encode())
            cert = run(['/usr/bin/openssl', 'x509', '-in', str(root/'cert.pem'), '-outform', 'DER'])
            fingerprint = hashlib.sha1(cert).hexdigest().upper()
            run(['/usr/bin/security', 'create-keychain', '-p', password, str(keychain)])
            run(['/usr/bin/security', 'set-keychain-settings', '-t', '600', '-l', str(keychain)])
            run(['/usr/bin/security', 'import', str(root/'identity.p12'), '-k', str(keychain),
                 '-f', 'pkcs12', '-P', password, '-x', '-T', '/usr/bin/codesign'])
            run(['/usr/bin/security', 'set-key-partition-list', '-S', 'apple-tool:', '-s', '-k', password, str(keychain)])
            private_file(STORE/'certificate.der', cert)
            private_file(STORE/'keychain-password', password.encode())
            identity = {'keychain':str(keychain), 'certificateSHA1':fingerprint, 'bundleIdentifier':IDENTIFIER,
                        'scope':'local development only; no system trust or TCC grant'}
            private_file(metadata, (json.dumps(identity, indent=2)+'\n').encode())
            return identity
    finally:
        run(['/usr/bin/security', 'list-keychains', '-d', 'user', '-s', *search])


def sign(app, allow_setup=False):
    app = app.resolve(strict=True)
    with (app/'Contents/Info.plist').open('rb') as source:
        info = plistlib.load(source)
    if info.get('CFBundleIdentifier') != IDENTIFIER:
        raise RuntimeError('Only the GalaxyControl local bundle may use this signer')
    # Generated bytecode is excluded from portable ZIPs; remove it before sealing.
    for cache in list(app.rglob('__pycache__')):
        if cache.is_dir() and not cache.is_symlink(): shutil.rmtree(cache)
    safe_store()
    identity = setup() if allow_setup else json.loads((STORE/'identity.json').read_text())
    password = (STORE/'keychain-password').read_text()
    keychain = identity['keychain']
    requirement = '=designated => identifier "'+IDENTIFIER+'" and certificate leaf = H"'+identity['certificateSHA1']+'"'
    search = [json.loads(line.strip()) for line in run(['/usr/bin/security', 'list-keychains', '-d', 'user']).decode().splitlines() if line.strip()]
    try:
        run(['/usr/bin/security', 'list-keychains', '-d', 'user', '-s', *search, keychain])
        run(['/usr/bin/security', 'unlock-keychain', '-p', password, keychain])
        run(['/usr/bin/codesign', '--force', '--sign', identity['certificateSHA1'], '--keychain', keychain,
             '--timestamp=none', '--requirements', requirement, str(app)])
        run(['/usr/bin/codesign', '--verify', '--deep', '--strict', str(app)])
        print(json.dumps({'signed':str(app), 'stableDesignatedRequirement':True, 'signatureVerified':True}))
    finally:
        run(['/usr/bin/security', 'lock-keychain', keychain])
        run(['/usr/bin/security', 'list-keychains', '-d', 'user', '-s', *search])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('app', type=pathlib.Path)
    parser.add_argument('--setup', action='store_true', help='Create an isolated local identity if absent')
    args = parser.parse_args()
    sign(args.app, args.setup)
